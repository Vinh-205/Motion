import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import * as Lucide from 'lucide';
import { iconToCubics, resampleIcon, buildPlan, allocOutputs, interpPolar, SPRING_PRESETS } from 'morphicons';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const glyphs = {
  radar: 'Radar', activity: 'Activity', timeline: 'ChartNoAxesCombined', history: 'History',
  users: 'Users', contact: 'ContactRound', sliders: 'SlidersHorizontal', settings: 'Settings2',
  orbit: 'Orbit', shield: 'Shield', shieldCheck: 'ShieldCheck', pause: 'Pause', play: 'Play',
  arrowUpRight: 'ArrowUpRight', info: 'Info', gauge: 'Gauge', rotate3d: 'Rotate3d', heart: 'Heart',
  user: 'UserRound', phone: 'Phone', radio: 'Radio', siren: 'Siren', check: 'Check',
  warning: 'TriangleAlert', bell: 'Bell', bellRing: 'BellRing', message: 'MessageSquare',
  mapPin: 'MapPin', close: 'X', circleCheck: 'CircleCheck', phoneCall: 'PhoneCall',
  navigation: 'Navigation', rotateCw: 'RotateCw', bookUser: 'BookUser', loader: 'LoaderCircle', arrowLeft: 'ArrowLeft',
  sun: 'Sun', moon: 'Moon',
};
export const pairs = [
  ['radar','activity'], ['timeline','history'], ['users','contact'], ['sliders','settings'],
  ['pause','shield'], ['shield','shieldCheck'], ['play','pause'], ['warning','siren'],
  ['heart','shieldCheck'], ['user','contact'], ['phone','phoneCall'], ['info','circleCheck'],
  ['arrowUpRight','check'], ['radio','radar'], ['message','check'], ['bell','bellRing'],
  ['mapPin','navigation'], ['gauge','activity'], ['rotate3d','rotateCw'], ['orbit','radar'],
  ['check','siren'], ['bookUser','contact'], ['siren','check'],
  ['sun','moon'],
];
const icons = {};
const plans = {};
const reference = {};
for (const [name, exported] of Object.entries(glyphs)) {
  if (!Array.isArray(Lucide[exported])) throw new Error(`Missing Lucide data: ${exported}`);
  icons[name] = iconToCubics(Lucide[exported]).map(({ pts, closed }) => ({ pts: [...pts], closed }));
}
for (const [from, to] of pairs) {
  const key = `${from}:${to}`;
  const plan = buildPlan(resampleIcon(Lucide[glyphs[from]]), resampleIcon(Lucide[glyphs[to]]));
  plans[key] = { n: plan.n, items: plan.items.map(({ aC,bT,ca,cb,theta,lnSigma,closed,block }) => ({ aC:[...aC], bT:[...bT], ca, cb, theta, lnSigma, closed, block })) };
  const out = allocOutputs(plan);
  reference[key] = [0, 0.25, 0.5, 0.75, 1, 1.08].map(t => { interpPolar(plan, t, out); return { t, points: out.map(row => [...row]) }; });
}
const rounded = (_key, value) => typeof value === 'number' ? Number(value.toFixed(8)) : value;
const data = { version: 'morphicons@2.0.0 / lucide@1.57.0', spring: SPRING_PRESETS.snappy, icons, plans };
mkdirSync(resolve(root,'lib/generated'), { recursive:true });
mkdirSync(resolve(root,'test/fixtures'), { recursive:true });
writeFileSync(resolve(root,'lib/generated/morphicons_data.g.dart'), '// GENERATED by tool/morphicons/generate.mjs. Do not edit.\n// Morph planning: morphicons (MIT); vectors: Lucide (ISC). See THIRD_PARTY_NOTICES.md.\n// ignore_for_file: type=lint\nconst Map<String, dynamic> morphiconsData = '+JSON.stringify(data)+';\n');
writeFileSync(resolve(root,'test/fixtures/morphicons_reference.json'), JSON.stringify(reference));
const licenses = [
  '# Third-party icon notices\n\nThis Flutter app uses vector data from Lucide. Morph plans are generated by the npm package morphicons; the native Flutter painter evaluates those plans. npm is a development-time tool, not an Android runtime dependency.\n',
  '## morphicons 2.0.0\n\n'+readFileSync(new URL('./node_modules/morphicons/LICENSE',import.meta.url),'utf8'),
  '## Lucide 1.57.0\n\n'+readFileSync(new URL('./node_modules/lucide/LICENSE',import.meta.url),'utf8'),
];
writeFileSync(resolve(root,'THIRD_PARTY_NOTICES.md'), licenses.join('\n'));
console.log(`Generated ${Object.keys(icons).length} vector icons and ${pairs.length} morph plans.`);

// Android system surfaces use the same Lucide source data as the Flutter icons.
const { cubicsToPathD } = await import('morphicons');
const drawable = resolve(root, 'android/app/src/main/res/drawable');
const vectorPath = name => cubicsToPathD(iconToCubics(Lucide[name]));
writeFileSync(resolve(drawable, 'ic_motion_notification.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/morphicons/generate.mjs; Lucide ISC license. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24"><path android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" android:strokeWidth="1.8" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="${vectorPath('Siren')}" /></vector>\n`);
writeFileSync(resolve(drawable, 'ic_motion_app.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/morphicons/generate.mjs; Lucide ISC license. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="24" android:viewportHeight="24"><path android:fillColor="#101412" android:pathData="M5,0H19Q24,0 24,5V19Q24,24 19,24H5Q0,24 0,19V5Q0,0 5,0Z"/><group android:pivotX="12" android:pivotY="12" android:scaleX="0.72" android:scaleY="0.72"><path android:fillColor="#00000000" android:strokeColor="#D4F58B" android:strokeWidth="1.8" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="${vectorPath('Orbit')}" /></group></vector>\n`);
