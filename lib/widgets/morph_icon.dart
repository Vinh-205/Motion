class MorphPlan {
  MorphPlan._(Map<String, dynamic> data)
    : _items = (data['items'] as List)
          .map((e) => _ContourPlan(Map<String, dynamic>.from(e as Map)))
          .toList();
  final List<_ContourPlan> _items;
  static final Map<String, MorphPlan> _cache = {};
  static MorphPlan? find(AppGlyph from, AppGlyph to) {
    final key = '${from.name}:${to.name}';
    final raw = (morphiconsData['plans'] as Map)[key];
    return raw == null
        ? null
        : _cache.putIfAbsent(
            key,
            () => MorphPlan._(Map<String, dynamic>.from(raw as Map)),
          );
  }

  List<Float64List> allocate() =>
      _items.map((e) => Float64List(e.a.length)).toList();

  /// Evaluates morphicons' polar plan, including its shared block transport.
  /// Matching, resampling and alignment are generated by the actual npm engine.
  void writePoints(double t, List<Float64List> output) {
    for (var k = 0; k < _items.length; k++) {
      final item = _items[k];
      final scale = math.exp(item.lnSigma * t);
      final cosine = math.cos(item.theta * t) * scale;
      final sine = math.sin(item.theta * t) * scale;
      final double cx, cy;
      if (item.block != null) {
        final offset = item.block!['off'] as List;
        final drift = item.block!['drift'] as List;
        final ox = (offset[0] as num).toDouble(),
            oy = (offset[1] as num).toDouble();
        cx = item.ca[0] + (drift[0] as num) * t + ox * cosine - oy * sine - ox;
        cy = item.ca[1] + (drift[1] as num) * t + ox * sine + oy * cosine - oy;
      } else {
        cx = item.ca[0] + (item.cb[0] - item.ca[0]) * t;
        cy = item.ca[1] + (item.cb[1] - item.ca[1]) * t;
      }
      for (var i = 0; i < item.a.length; i += 2) {
        final px = item.a[i] + (item.b[i] - item.a[i]) * t;
        final py = item.a[i + 1] + (item.b[i + 1] - item.a[i + 1]) * t;
        output[k][i] = cx + px * cosine - py * sine;
        output[k][i + 1] = cy + px * sine + py * cosine;
      }
    }
  }
}

class _ContourPlan {
  _ContourPlan(Map<String, dynamic> data)
    : a = _numbers(data['aC']),
      b = _numbers(data['bT']),
      ca = _numbers(data['ca']),
      cb = _numbers(data['cb']),
      theta = (data['theta'] as num).toDouble(),
      lnSigma = (data['lnSigma'] as num).toDouble(),
      closed = data['closed'] as bool,
      block = data['block'] as Map?;
  final List<double> a, b, ca, cb;
  final double theta, lnSigma;
  final bool closed;
  final Map? block;
  static List<double> _numbers(dynamic raw) =>
      (raw as List).map((v) => (v as num).toDouble()).toList();
}

final Map<AppGlyph, List<Path>> _staticPaths = {};
List<Path> _paths(AppGlyph glyph) => _staticPaths.putIfAbsent(glyph, () {
  final contours = (morphiconsData['icons'] as Map)[glyph.name] as List;
  return contours.map((raw) {
    final points = ((raw as Map)['pts'] as List)
        .map((p) => (p as num).toDouble())
        .toList();
    final path = Path()..moveTo(points[0], points[1]);
    for (var i = 2; i < points.length; i += 6) {
      path.cubicTo(
        points[i],
        points[i + 1],
        points[i + 2],
        points[i + 3],
        points[i + 4],
        points[i + 5],
      );
    }
    if (raw['closed'] == true) path.close();
    return path;
  }).toList();
});

/// Flutter-native renderer for npm morphicons-generated geometry. No WebView.
class MorphIcon extends StatefulWidget {
  const MorphIcon(
    this.glyph, {
    super.key,
    this.alternate,
    this.active = false,
    this.size = 24,
    this.color,
    this.strokeWidth = 1.8,
    this.semanticLabel,
  });
  final AppGlyph glyph;
  final AppGlyph? alternate;
  final bool active;
  final double size, strokeWidth;
  final Color? color;
  final String? semanticLabel;
  @override
  State<MorphIcon> createState() => _MorphIconState();
}

class _MorphIconState extends State<MorphIcon> with TickerProviderStateMixin {
  late final AnimationController _shape = AnimationController.unbounded(
    vsync: this,
    value: widget.active ? 1 : 0,
  );
  late final AnimationController _draw = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 420),
  );
  late final Listenable _repaint = Listenable.merge([_shape, _draw]);
  MorphPlan? _plan;
  List<Float64List> _buffers = [];
  bool _mountedAnimation = false;
  @override
  void initState() {
    super.initState();
    _resolvePlan();
  }

  void _resolvePlan() {
    _plan = widget.alternate == null
        ? null
        : MorphPlan.find(widget.glyph, widget.alternate!);
    _buffers = _plan?.allocate() ?? [];
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    if (MediaQuery.disableAnimationsOf(context)) {
      _shape.stop();
      _shape.value = widget.active ? 1 : 0;
      _draw.value = 1;
    } else if (!_mountedAnimation) {
      _draw.forward();
    }
    _mountedAnimation = true;
  }

  @override
  void didUpdateWidget(covariant MorphIcon oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (oldWidget.glyph != widget.glyph ||
        oldWidget.alternate != widget.alternate) {
      _resolvePlan();
    }
    if (oldWidget.active != widget.active ||
        oldWidget.glyph != widget.glyph ||
        oldWidget.alternate != widget.alternate) {
      final target = widget.active ? 1.0 : 0.0;
      if (MediaQuery.disableAnimationsOf(context) || _plan == null) {
        _shape.value = target;
      } else {
        final spring = morphiconsData['spring'] as Map;
        _shape.animateWith(
          SpringSimulation(
            SpringDescription(
              mass: 1,
              stiffness: (spring['k'] as num).toDouble(),
              damping: (spring['c'] as num).toDouble(),
            ),
            _shape.value,
            target,
            _shape.velocity,
          ),
        );
      }
    }
  }

  @override
  void dispose() {
    _shape.dispose();
    _draw.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) => Semantics(
    label: widget.semanticLabel,
    image: widget.semanticLabel != null,
    child: ExcludeSemantics(
      child: RepaintBoundary(
        child: SizedBox(
          width: widget.size,
          height: widget.size,
          child: Center(
            child: SizedBox(
              width: widget.size,
              height: widget.size,
              child: CustomPaint(
                painter: _MorphPainter(
                  glyph: widget.glyph,
                  alternate: widget.alternate,
                  active: widget.active,
                  shape: _shape,
                  draw: _draw,
                  repaint: _repaint,
                  plan: _plan,
                  buffers: _buffers,
                  color:
                      widget.color ??
                      IconTheme.of(context).color ??
                      Theme.of(context).colorScheme.onSurface,
                  strokeWidth: widget.strokeWidth,
                ),
              ),
            ),
          ),
        ),
      ),
    ),
  );
}

class _MorphPainter extends CustomPainter {
  _MorphPainter({
    required this.glyph,
    required this.alternate,
    required this.active,
    required this.shape,
    required this.draw,
    required Listenable repaint,
    required this.plan,
    required this.buffers,
    required this.color,
    required this.strokeWidth,
  }) : super(repaint: repaint);
  final AppGlyph glyph;
  final AppGlyph? alternate;
  final bool active;
  final AnimationController shape, draw;
  final MorphPlan? plan;
  final List<Float64List> buffers;
  final Color color;
  final double strokeWidth;
  @override
  void paint(Canvas canvas, Size size) {
    canvas.save();
    canvas.scale(size.width / 24, size.height / 24);
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = strokeWidth
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round
      ..isAntiAlias = true;
    List<Path> paths;
    if (plan != null && shape.isAnimating) {
      plan!.writePoints(shape.value, buffers);
      paths = [
        for (var k = 0; k < buffers.length; k++)
          _polyline(buffers[k], plan!._items[k].closed),
      ];
    } else {
      paths = _paths(active && alternate != null ? alternate! : glyph);
    }
    for (final path in paths) {
      if (draw.value >= 0.999) {
        canvas.drawPath(path, paint);
      } else {
        for (final metric in path.computeMetrics()) {
          canvas.drawPath(
            metric.extractPath(
              0,
              metric.length * Curves.easeOutCubic.transform(draw.value),
            ),
            paint,
          );
        }
      }
    }
    canvas.restore();
  }

  Path _polyline(Float64List pts, bool closed) {
    final path = Path()..moveTo(pts[0], pts[1]);
    for (var i = 2; i < pts.length; i += 2) {
      path.lineTo(pts[i], pts[i + 1]);
    }
    if (closed) path.close();
    return path;
  }

  @override
  bool shouldRepaint(covariant _MorphPainter old) =>
      old.glyph != glyph ||
      old.alternate != alternate ||
      old.active != active ||
      old.color != color ||
      old.strokeWidth != strokeWidth ||
      old.shape != shape ||
      old.draw != draw;
}
